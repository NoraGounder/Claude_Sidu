// Packs everything in ./site into src/site-files.js so the Worker can serve it
// without the separate static-assets upload step. Run automatically by `wrangler deploy`.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { createHash } from 'node:crypto';

const ROOT = new URL('../site/', import.meta.url).pathname;
const OUT = new URL('../src/site-files.js', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.woff2': 'font/woff2', '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8', '.json': 'application/json',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = {};
for (const file of walk(ROOT)) {
  const rel = '/' + relative(ROOT, file).split('\\').join('/');
  if (rel.split('/').some((seg) => seg.startsWith('_') || seg.startsWith('.'))) continue;
  const buf = readFileSync(file);
  files[rel] = {
    type: TYPES[extname(file)] || 'application/octet-stream',
    etag: '"' + createHash('sha256').update(buf).digest('hex').slice(0, 16) + '"',
    b64: buf.toString('base64'),
  };
}
writeFileSync(OUT, '// Generated by scripts/build.mjs. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`Packed ${Object.keys(files).length} files from site/ into src/site-files.js`);
